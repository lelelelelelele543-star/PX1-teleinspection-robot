#!/usr/bin/env python3
"""Render the ACTUAL generated PX1_Current_Master.step, never substitute schematic solids.
Usage: python current/CAD/render_current_master.py
Requires: cadquery, vtk; STEP generated by PX1_Current_Master.py.
"""
from pathlib import Path
import sys
import gzip
import shutil
import tempfile
import cadquery as cq
import vtk
ROOT=Path(__file__).resolve().parent
STEP=ROOT/"PX1_Current_Master.step"
OUT=ROOT/"previews"/"PX1_Current_Master_REAL.png"
GZ = STEP.with_suffix(".step.gz")
with tempfile.TemporaryDirectory(prefix="px1-step-") as tmp:
    if GZ.is_file():
        source = Path(tmp) / STEP.name
        with gzip.open(GZ, "rb") as src, source.open("wb") as dst:
            shutil.copyfileobj(src, dst)
    elif STEP.is_file():
        source = STEP
    else:
        raise SystemExit("NOT_RUN: missing master STEP and STEP.GZ")
    shapes = cq.importers.importStep(str(source)).vals()
if not shapes: raise SystemExit("FAIL: STEP has no shapes")
append=vtk.vtkAppendPolyData()
count=0
for shape in shapes:
    verts,triangles=shape.tessellate(.5,.2)
    if not triangles:continue
    pts=vtk.vtkPoints()
    for p in verts:pts.InsertNextPoint(p.x,p.y,p.z)
    polys=vtk.vtkCellArray()
    for a,b,c in triangles:
        polys.InsertNextCell(3);polys.InsertCellPoint(a);polys.InsertCellPoint(b);polys.InsertCellPoint(c)
    poly=vtk.vtkPolyData();poly.SetPoints(pts);poly.SetPolys(polys);append.AddInputData(poly)
    count+=1
if count==0:raise SystemExit("FAIL: no tessellated solids")
append.Update()
mapper=vtk.vtkPolyDataMapper();mapper.SetInputConnection(append.GetOutputPort())
actor=vtk.vtkActor();actor.SetMapper(mapper);actor.GetProperty().SetColor(.73,.77,.81)
actor.GetProperty().SetInterpolationToPhong()
ren=vtk.vtkRenderer();ren.SetBackground(.08,.12,.18);ren.AddActor(actor)
ren.SetUseFXAA(True)
window=vtk.vtkRenderWindow();window.SetOffScreenRendering(1);window.SetSize(1600,1000);window.AddRenderer(ren)
camera=ren.GetActiveCamera();camera.SetPosition(600,-550,440);camera.SetFocalPoint(150,0,70);camera.SetViewUp(0,0,1)
ren.ResetCamera();camera.Zoom(1.3)
window.Render()
w2i=vtk.vtkWindowToImageFilter();w2i.SetInput(window);w2i.Update()
OUT.parent.mkdir(parents=True,exist_ok=True)
writer=vtk.vtkPNGWriter();writer.SetFileName(str(OUT));writer.SetInputConnection(w2i.GetOutputPort());writer.Write()
print(f"PASS: rendered {count} actual STEP shapes to {OUT}")
